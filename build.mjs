// dsh-alexandrie — client bundle build.
//
// The DSH Web shell loads one browser artifact per plugin (the "./client" export), so the
// readable, reviewable source in src/client/ is concatenated (in filename order) into
// lib/client.js inside the __ModuleLoader__ factory wrapper. No bundler, no JSX:
// every part is plain JavaScript and React.Element calls go through `h`.

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'

const sourceDir = new URL('./src/client/', import.meta.url)
const outFile = new URL('./lib/client.js', import.meta.url)

const files = (await readdir(sourceDir)).filter((file) => file.endsWith('.js')).sort()
if (files.length === 0) throw new Error('no client source parts found')

const parts = []
for (const file of files) {
  const text = await readFile(new URL(file, sourceDir), 'utf8')
  parts.push(`// >>>>>>>>>>>>>>>>>>>>>>>>>>>> ${file} >>>>>>>>>>>>>>>>>>>>>>>>>>>>\n${text.trimEnd()}\n`)
}

const banner = `// dsh-alexandrie — browser half (generated by build.mjs; edit src/client/*.js instead).
window.__ModuleLoader__.load({
  id: 'dsh-alexandrie',
  factory: (require) => {
`
const footer = `
    return { inject: ['slots'], apply }
  },
})
`

const body = parts.join('\n')
await mkdir(new URL('./lib/', import.meta.url), { recursive: true })
await writeFile(outFile, banner + body + footer, 'utf8')
console.log(`built lib/client.js from ${files.length} parts (${Buffer.byteLength(banner + body + footer)} bytes)`)
